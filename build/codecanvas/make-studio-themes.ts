fs.writeFileSync(path.join(themesFolder, 'studio-light-color-theme.json'), JSON.stringify(theme('Studio Light', STUDIO_LIGHT, STUDIO_KINDS_LIGHT, STUDIO_JSON_LIGHT, false), null, '\t') + '\n');
